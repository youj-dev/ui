// Per-component label modules for copy-in.
//
// The single source of truth stays where it was: the keys and their types in
// core's labels-types.ts, the English values in labels-defaults.ts, and which
// keys each component reads in packages/core/scripts/label-groups.json. From
// those this writes
//   - src/lib/youj/labels/<component>.ts      one self-contained module per group (keys, types, defaults)
//   - src/lib/youj/labels-components.ts       the barrel that keeps the `@youj/core/labels` entry as it was
//   - registry/stubs/labels.ts                the full dictionary for youj-labels, composed from the modules
//   - registry/labels-components.json         one registry item per module (youj-labels-<component>)
// and adds each item to the registryDependencies of every registry item whose
// files import that group, so a copied Button brings its own `loading` and nothing else.
//
// Run from the repo root (`node scripts/generate-labels.mjs`) or from packages/core (`pnpm labels:generate`):
// paths resolve from this file, not from the working directory.
//   node scripts/generate-labels.mjs          write
//   node scripts/generate-labels.mjs --check  exit 1 when anything is out of date
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import ts from 'typescript'
import { readTextIfExists } from './read-text.mjs'

const check = process.argv.includes('--check')
const packages = join(import.meta.dirname, '../packages')
const core = join(packages, 'core')
const lib = join(core, 'src/lib/youj')
const stale = []

const write = (path, content) => {
  if (readTextIfExists(path) === content) return
  stale.push(path.slice(core.length - 'packages/core'.length + 0))
  if (!check) {
    mkdirSync(join(path, '..'), { recursive: true })
    writeFileSync(path, content)
  }
}

const parse = (path) => ts.createSourceFile(path, readFileSync(path, 'utf8'), ts.ScriptTarget.Latest, true)
const flat = (text) => text.replace(/\s+/g, ' ').trim()

// key → type text, from the YoujLabels interface
const types = new Map()
for (const node of parse(join(lib, 'labels-types.ts')).statements) {
  if (!ts.isInterfaceDeclaration(node) || node.name.text !== 'YoujLabels') continue
  for (const member of node.members) types.set(member.name.text, flat(member.type.getText()))
}

// key → initializer text, from labels-defaults.ts (`continue` lives under `continueLabel`: a keyword can't be an export)
const defaults = new Map()
// Helpers a default calls (`nounFor`): copied into each module that does.
const helpers = new Map()
for (const node of parse(join(lib, 'labels-defaults.ts')).statements) {
  if (ts.isFunctionDeclaration(node)) helpers.set(node.name.text, node.getFullText().trim())
  if (!ts.isVariableStatement(node)) continue
  const decl = node.declarationList.declarations[0]
  const key = /YoujLabels\['(\w+)'\]/.exec(decl.type.getText())[1]
  defaults.set(key, decl.initializer.getText())
}

// `components` are the groups a component reads (exported from @youj/core/labels); `dictionaryOnly`
// holds the keys only useLabels() reads (blocks), which belong to the full dictionary and no public export.
const { components, dictionaryOnly } = JSON.parse(readFileSync(join(core, 'scripts/label-groups.json'), 'utf8'))
const groups = { ...components, ...dictionaryOnly }
const problems = []
for (const [name, keys] of Object.entries(groups)) {
  for (const key of keys) {
    if (!types.has(key)) problems.push(`${name}: "${key}" is not a YoujLabels key`)
    if (!defaults.has(key)) problems.push(`${name}: "${key}" has no English default`)
  }
}
const grouped = new Set(Object.values(groups).flat())
for (const key of types.keys()) if (!grouped.has(key)) problems.push(`"${key}" is read by no component group (add it to a group in label-groups.json)`)
if (problems.length) {
  console.error(problems.map((p) => `  ✗ ${p}`).join('\n'))
  process.exit(1)
}

const kebab = (name) => name.replace(/Labels$/, '').replace(/([a-z0-9])([A-Z])/g, '$1-$2').toLowerCase()
// A module is named for its export (`dataTableBodyLabels.ts`): a shorter name like `button.ts` would be re-pointed by `shadcn add` at the same-named component, and a kebab path with `data-` would read as an attribute to check-surface.
const fileOf = (name) => name
const HEADER = '// Generated by scripts/generate-labels.mjs from labels-types.ts, labels-defaults.ts and label-groups.json. Do not edit.\n'

// 1. one module per group
const modulesDir = join(lib, 'labels')
const wanted = new Set()
for (const [name, keys] of Object.entries(groups)) {
  const file = `${fileOf(name)}.ts`
  wanted.add(file)
  const shape = keys.map((k) => `${k}: ${types.get(k)}`).join('; ')
  const body = keys.map((k) => `  ${k}: ${defaults.get(k)},`).join('\n')
  const used = [...helpers].filter(([helper]) => keys.some((k) => new RegExp(`\\b${helper}\\(`).test(defaults.get(k)))).map(([, text]) => `\n${text}\n`)
  write(join(modulesDir, file), `${HEADER}\nexport const ${name} = {\n${body}\n} satisfies { ${shape} }\n${used.join('')}`)
}
if (existsSync(modulesDir)) {
  for (const file of readdirSync(modulesDir)) {
    if (wanted.has(file)) continue
    stale.push(`src/lib/youj/labels/${file}`)
    if (!check) rmSync(join(modulesDir, file))
  }
}

// 2. the barrel, so `@youj/core/labels` exports the same names
write(
  join(lib, 'labels-components.ts'),
  `${HEADER}\n${Object.keys(components)
    .map((name) => `export { ${name} } from './labels/${fileOf(name)}'`)
    .join('\n')}\n`,
)

// 3. youj-labels' copy of labels.ts: the whole dictionary, from the modules
const names = Object.keys(groups)
write(
  join(core, 'registry/stubs/labels.ts'),
  `${HEADER}import type { YoujLabels } from './labels-types'\n${names.map((n) => `import { ${n} } from './labels/${fileOf(n)}'`).join('\n')}\n\nexport type { YoujLabels } from './labels-types'\n\n/** Every English string, composed from the per-component modules this copy brought. */\nexport const defaultLabels: YoujLabels = {\n${names.map((n) => `  ...${n},`).join('\n')}\n}\n`,
)

// 4. one registry item per module
const itemOf = (name) => `youj-labels-${kebab(name)}`
const items = names.map((name) => ({
  name: itemOf(name),
  type: 'registry:lib',
  title: `${name.replace(/Labels$/, '')} labels`,
  description: `The English strings of ${name.replace(/Labels$/, '')} (${groups[name].join(', ')}), for useComponentLabels. Installed with the component that reads them.`,
  files: [{ path: `src/lib/youj/labels/${fileOf(name)}.ts`, type: 'registry:lib' }],
}))
write(join(core, 'registry/labels-components.json'), JSON.stringify(items, null, 2) + '\n')

// 5. every registry item that imports a group depends on its module (and no other)
const IMPORT = /import\s*(?:type\s*)?\{([^}]*)\}\s*from\s*['"](?:@youj\/core\/labels|@youj\/core\/lib\/youj\/labels-components|\.\/labels-components)['"]/g
const ours = new Set(names.map(itemOf))
for (const pkg of readdirSync(packages)) {
  const dir = join(packages, pkg, 'registry')
  if (!existsSync(dir)) continue
  for (const fragment of readdirSync(dir).filter((f) => f.endsWith('.json'))) {
    const path = join(dir, fragment)
    // UI's items are generated (packages/ui/scripts/generate.mjs) and follow the labels each file imports.
    if (path.endsWith('registry/labels-components.json') || path.endsWith('ui/registry/ui.json')) continue
    const raw = readFileSync(path, 'utf8')
    const list = JSON.parse(raw)
    let touched = false
    const changed = []
    for (const item of list) {
      const needs = new Set(item.name === 'youj-labels' ? ours : [])
      for (const f of item.files ?? []) {
        if (!/\.tsx?$/.test(f.path) || !existsSync(join(packages, pkg, f.path))) continue
        for (const [, imported] of readFileSync(join(packages, pkg, f.path), 'utf8').matchAll(IMPORT)) {
          for (const part of imported.split(',')) {
            const name = part.trim().split(/\s+as\s+/)[0]
            if (name in components) needs.add(itemOf(name))
          }
        }
      }
      const before = item.registryDependencies ?? []
      // A label module that's gone (its group was renamed or removed) leaves no dependency behind.
      const after = [...before.filter((d) => !ours.has(d) && !d.startsWith('youj-labels-')), ...[...needs].sort()]
      if (after.length && after.join() !== before.join()) {
        const sorted = [...before].sort().join() === before.join()
        item.registryDependencies = sorted ? after.sort() : after
        touched = true
        changed.push(item)
      } else if (!after.length && before.length !== after.length) {
        delete item.registryDependencies
        touched = true
        changed.push(item)
      }
    }
    if (touched) {
      if (JSON.stringify(JSON.parse(raw), null, 2) + '\n' === raw) write(path, JSON.stringify(list, null, 2) + '\n')
      else {
        // Hand-formatted fragment: say what's missing rather than reformat it.
        console.error(`${path}: hand-formatted, so set registryDependencies yourself:`)
        for (const item of changed) console.error(`  ${item.name}: ${JSON.stringify(item.registryDependencies ?? [])}`)
        process.exit(1)
      }
    }
  }
}

if (stale.length) {
  if (check) {
    console.error(`labels: out of date (run pnpm labels:generate):\n${stale.map((p) => `  ✗ ${p}`).join('\n')}`)
    process.exit(1)
  }
  console.log(`labels: wrote ${stale.length} file(s)`)
} else console.log(`labels: ${names.length} modules up to date`)
