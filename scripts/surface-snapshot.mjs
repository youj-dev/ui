// The public CSS surface as a committed snapshot, api/youj-surface.md: the
// custom properties the shipped stylesheets declare (minus the private `--ui--`
// ones) and the `data-` attributes the packages' source writes or selects
// (Youj's `data-yj-*`, and the standard ones from check-surface.mjs).
//
//   pnpm api:update   regenerate after an intended change, then commit api/
//   pnpm check:api    fail when the surface changed and the snapshot didn't
//
// A diff here is the review prompt: a removed or renamed name breaks users'
// selectors and overrides, so it is a breaking change (see docs guides/styling-hooks).
import { execFileSync } from 'node:child_process'
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { pathToFileURL } from 'node:url'
import { STANDARD } from './check-surface.mjs'

/** The non-private custom properties a stylesheet declares, sorted. */
export function declaredVariables(css) {
  const names = new Set([...css.matchAll(/(?:^|[;{\s])(--[A-Za-z0-9][A-Za-z0-9_-]*)\s*:/g)].map((m) => m[1]))
  return [...names].filter((n) => !n.startsWith('--tw-') && !n.startsWith('--ui--')).sort()
}

/** The `data-yj-*` names and the standard `data-` names in `text`. */
export function usedAttributes(text) {
  const own = new Set()
  const standard = new Set()
  for (const m of text.matchAll(/(?<![\w-])data-([a-z][a-z0-9]*(?:-[a-z0-9]+)*)/g)) {
    if (m[1].startsWith('yj-')) own.add(`data-${m[1]}`)
    else if (STANDARD.has(m[1])) standard.add(`data-${m[1]}`)
  }
  return { own, standard }
}

const NOT_SHIPPED = /(^|\/)(node_modules|dist|\.next|public|fixtures|__fixtures__|test)\/|\.(test|stories|ssr-cases)\.(tsx?|css)$/

function shippedFiles(root, ext) {
  return execFileSync('git', ['ls-files', '-co', '--exclude-standard', '-z', 'packages'], { cwd: root, encoding: 'utf8', maxBuffer: 1 << 28 })
    .split('\0')
    .filter((f) => /^packages\/[^/]+\/src\//.test(f) && ext.test(f) && !NOT_SHIPPED.test(f))
}

export function snapshotSurface(root) {
  const out = ['# Public CSS surface', '', 'Generated by scripts/surface-snapshot.mjs. Do not edit by hand.', '', '## CSS variables', '']
  for (const file of shippedFiles(root, /\.css$/).sort()) {
    const names = declaredVariables(readFileSync(join(root, file), 'utf8'))
    if (names.length) out.push(`### ${file}`, '', ...names.map((n) => `- ${n}`), '')
  }
  const own = new Set()
  const standard = new Set()
  for (const file of shippedFiles(root, /\.(?:tsx?|css)$/)) {
    const used = usedAttributes(readFileSync(join(root, file), 'utf8'))
    for (const n of used.own) own.add(n)
    for (const n of used.standard) standard.add(n)
  }
  out.push('## Attributes', '', '### data-yj-*', '', ...[...own].sort().map((n) => `- ${n}`), '', '### Standard', '', ...[...standard].sort().map((n) => `- ${n}`), '')
  return out.join('\n')
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const root = join(import.meta.dirname, '..')
  const file = join(root, 'api', 'youj-surface.md')
  const text = snapshotSurface(root)
  const current = existsSync(file) ? readFileSync(file, 'utf8') : null
  if (process.argv.includes('--check')) {
    if (current !== text) {
      const a = new Set((current ?? '').split('\n'))
      const b = new Set(text.split('\n'))
      const lines = [...[...a].filter((l) => l.trim() && !b.has(l)).map((l) => `- ${l}`), ...[...b].filter((l) => l.trim() && !a.has(l)).map((l) => `+ ${l}`)]
      console.error(`The public CSS surface changed, and its snapshot didn't:\n\n${lines.slice(0, 20).join('\n')}\n\nIf the change is intended: pnpm api:update, commit api/, and add a changeset.`)
      process.exit(1)
    }
    console.log('surface: snapshot current')
  } else if (current !== text) {
    mkdirSync(dirname(file), { recursive: true })
    writeFileSync(file, text)
    console.log('surface: wrote api/youj-surface.md')
  } else console.log('surface: up to date')
}
