// The Glass pack's cues as the sound loop draws and plays them: each MP3 exactly as the SoundProvider gets it,
// decoded with ffmpeg and started where the player starts it. Run it after the pack changes:
//   pnpm -F promo cues        writes src/loops/sound-cues.ts (the waveforms the scene draws)
import { execFileSync } from 'node:child_process'
import { createHash } from 'node:crypto'
import { writeFileSync } from 'node:fs'
import path from 'node:path'

const root = path.resolve(import.meta.dirname, '..')
const PACK = path.resolve(root, '../../packages/sound/src/packs/glass.data.ts')

export const RATE = 48_000
/** The player's start (packages/sound/src/lib/player.ts): the first sample within 50 dB of the peak, less a millisecond of lead. */
const ONSET_DB = -50
const LEAD = 0.001
/** Waveform bins per second: at the loop's closest view a bin is a third of a pixel. */
export const BINS = 2000

const sha1 = (text) => createHash('sha1').update(text).digest('hex').slice(0, 12)

/** Every cue of the Glass pack: its candidate, the hash of its bytes, and its samples from where the player starts it. */
export async function decodePack() {
  const { picks, sounds } = await import(PACK)
  return Object.fromEntries(
    Object.entries(sounds).map(([cue, base64]) => {
      const raw = execFileSync('ffmpeg', ['-hide_banner', '-loglevel', 'error', '-f', 'mp3', '-i', 'pipe:0', '-f', 'f32le', '-ac', '1', '-ar', String(RATE), 'pipe:1'], {
        input: Buffer.from(base64, 'base64'),
        maxBuffer: 1 << 26,
      })
      const all = new Float32Array(raw.length / 4)
      for (let i = 0; i < all.length; i++) all[i] = raw.readFloatLE(i * 4)
      let top = 0
      for (const x of all) top = Math.max(top, Math.abs(x))
      const threshold = top * 10 ** (ONSET_DB / 20)
      let first = 0
      while (first < all.length && Math.abs(all[first]) <= threshold) first++
      const start = Math.max(0, first - Math.round(LEAD * RATE))
      return [cue, { pick: picks[cue], source: sha1(base64), samples: all.subarray(start) }]
    }),
  )
}

/** A cue's waveform: the highest and lowest sample in each bin, in thousandths of full scale. */
function waveform(samples) {
  const per = RATE / BINS
  const max = []
  const min = []
  for (let at = 0; at < samples.length; at += per) {
    let hi = 0
    let lo = 0
    for (let i = Math.floor(at); i < Math.min(samples.length, Math.floor(at + per)); i++) {
      hi = Math.max(hi, samples[i])
      lo = Math.min(lo, samples[i])
    }
    max.push(Math.round(hi * 1000))
    min.push(Math.round(lo * 1000))
  }
  // Trailing silence draws nothing.
  while (max.length > 1 && max.at(-1) === 0 && min.at(-1) === 0) {
    max.pop()
    min.pop()
  }
  return { max, min }
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const pack = await decodePack()
  const cues = Object.entries(pack).map(([cue, { pick, source, samples }]) => {
    const { max, min } = waveform(samples)
    return `  ${cue}: {\n    pick: '${pick}',\n    source: '${source}',\n    max: [${max.join(',')}],\n    min: [${min.join(',')}],\n  },`
  })
  const file = path.join(root, 'src/loops/sound-cues.ts')
  writeFileSync(
    file,
    `// Generated by scripts/cues.mjs from the Glass pack (packages/sound/src/packs/glass.data.ts). Run \`pnpm -F promo cues\` after the pack changes.\n` +
      `// Each cue is the MP3 the SoundProvider plays, decoded, from the sample the player starts it at: the highest and lowest\n` +
      `// sample in each bin of 1/${BINS} s, in thousandths of full scale. \`source\` is a hash of the file's bytes, so a test can tell when it's stale.\n\n` +
      `export const CUE_BINS = ${BINS}\n\n` +
      `export const GLASS = {\n${cues.join('\n')}\n}\n`,
  )
  console.log(`▸ ${path.relative(root, file)}: ${Object.keys(pack).length} cues`)
}
