// Writes generated/palette-art.ts: every Youj icon and every illustration scene, by its id, as a chunk of its own, for
// the search palette's stage, which draws the highlighted result live. Neither the palette nor a page carries the sets:
// the stage fetches the one icon or the one scene's file it's showing. Read from the packages' own sources (the icon
// index, the scene registry), so an icon or a scene added there shows up here with nothing else to edit.
import { readPackageFile as source, report, writeGenerated } from './lib.ts'

// `import { BellIcon } from './bell'`: the icon `bell`, exported as BellIcon.
const iconIndex = source('icons/src/components/youj/icons/index.ts')
const icons = [...iconIndex.matchAll(/^import \{ (\w+Icon) \} from '\.\/([\w-]+)'$/gm)]
  .map(([, name, file]) => `  '${file}': () => import('@youj/icons/components/youj/icons/${file}').then((m) => m.${name}),`)
  .sort()

// The registry imports each scene from its category's file and lists it by id: `{ id: 'database', … Component: IllustrationDatabase }`.
const registry = source('illustrations/src/components/youj/graphics/illustrations/registry.tsx')
const fileOf = new Map<string, string>()
for (const [, names, file] of registry.matchAll(/^import \{ ([\w, ]+) \} from '\.\/([\w/-]+)'$/gm))
  for (const name of names!.split(/,\s*/)) fileOf.set(name, file!)
const scenes = [...registry.matchAll(/\{ id: '([\w-]+)'[^\n]*Component: (Illustration\w+) \}/g)]
  .filter(([, , name]) => fileOf.has(name!))
  .map(
    ([, id, name]) =>
      `  '${id}': () => import('@youj/illustrations/components/youj/graphics/illustrations/${fileOf.get(name!)}').then((m) => m.${name}),`,
  )

// The patterns above read the sources as text: when a source's formatting drifts, fail rather than quietly drop entries.
const count = (text: string, pattern: RegExp) => [...text.matchAll(pattern)].length
if (icons.length !== count(iconIndex, /^import \{ \w+Icon \}/gm))
  throw new Error('palette art: some icon imports in the icon index no longer match the pattern in scripts/palette-art.ts')
if (scenes.length !== count(registry, /Component: Illustration/g))
  throw new Error('palette art: some scenes in the registry no longer match the pattern in scripts/palette-art.ts')

writeGenerated(
  'palette-art.ts',
  `// Generated by scripts/palette-art.ts. Do not edit by hand.
import type { ComponentType } from 'react'
import type { YoujIconComponent } from '@youj/icons'
import type { IllustrationProps } from '@youj/illustrations'

/** Every Youj icon by its name, each fetched as a chunk of its own. */
export const ICONS: Record<string, () => Promise<YoujIconComponent>> = {
${icons.join('\n')}
}

/** Every illustration scene by its id, each fetched with its category's file. */
export const SCENES: Record<string, () => Promise<ComponentType<IllustrationProps>>> = {
${scenes.join('\n')}
}
`,
)
report('palette art', `${icons.length} icons and ${scenes.length} scenes → generated/palette-art.ts`)
