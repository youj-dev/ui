// Writes generated/loaders.ts: every loader's component, by its id, as a chunk of its
// own entry (`@youj/loaders/<id>`). The loaders page fetches the one on its stage and
// each thumbnail's as it comes near, so neither the page nor a visit carries the whole
// set. The list is the package's exports, so a loader added there shows up here with
// nothing else to edit.
import { readPackageFile, report, writeGenerated } from './lib.ts'

const manifest = JSON.parse(readPackageFile('loaders/package.json')) as { exports: Record<string, string> }
const pascal = (id: string) => id.replace(/(^|-)([a-z0-9])/g, (_, __, c: string) => c.toUpperCase())

const lines = Object.keys(manifest.exports)
  .filter((key) => key !== '.')
  .map((key) => key.slice(2))
  .sort()
  .map((id) => `  '${id}': () => import('@youj/loaders/${id}').then((m) => m.Loader${pascal(id)}),`)

writeGenerated(
  'loaders.ts',
  `// Generated by scripts/loaders.ts. Do not edit by hand.
import type { ComponentType } from 'react'
import type { LoaderProps } from '@youj/loaders'

export type LoaderComponent = ComponentType<LoaderProps>

/** Every loader by its id, each fetched as a chunk of its own. */
export const LOADERS: Record<string, () => Promise<LoaderComponent>> = {
${lines.join('\n')}
}
`,
)
report('loaders', `${lines.length} → generated/loaders.ts`)
