// Writes generated/showcase.tsx: one loader per block, keyed
// `blocks/<slug>`, for the bare /view pages the docs
// frame in an iframe, and one per component (`component/<slug>`: its docs demo). The list comes from lib/showcase.ts (the registry's
// blocks), so new ones need no docs edit.
// Also writes generated/showcase-code.json: each one's files as `shadcn add`
// installs them, keyed the same way, for the Code tab and its .zip.
import { basics } from '../lib/basics.ts'
import { blocks } from '../lib/showcase.ts'
import { installedFiles } from './installed-files.ts'
import { report, writeGenerated } from './lib.ts'

const entries = blocks()

const components = basics().filter((e) => e.demo)
const lines = [
  ...entries.map((e) => `  '${e.kind}/${e.slug}': () => import('${e.module}'),`),
  ...components.map((e) => `  '${e.kind}/${e.slug}': () => import('@/examples/${e.demo}'),`),
]
const file = `'use client'
// Generated by scripts/showcase.ts. Do not edit by hand.
// Story modules, typed loosely: each file's Meta is typed by its own component.
export const showcase: Record<string, () => Promise<unknown>> = {
${lines.join('\n')}
}
`

// Every other live example on a component's docs page, by name (`button/sizes`): the viewer's stories for
// /view/component/<slug>?story=button/sizes. A file of its own, imported only when one is asked for, so /view carries none of it.
const demos = [...new Set(components.flatMap((e) => e.demos.map((d) => d.id)))]
const demoFile = `'use client'
// Generated by scripts/showcase.ts. Do not edit by hand.
export const demos: Record<string, () => Promise<unknown>> = {
${demos.map((name) => `  '${name}': () => import('@/examples/${name}'),`).join('\n')}
}
`

writeGenerated('showcase.tsx', file)
writeGenerated('demos.tsx', demoFile)
const code = Object.fromEntries(entries.map((e) => [`${e.kind}/${e.slug}`, installedFiles(e.files)]))
writeGenerated('showcase-code.json', JSON.stringify(code))
report('showcase', `${blocks().length} blocks → generated/showcase.tsx`)
