'use client'

import { lazy, type ComponentType, type LazyExoticComponent } from 'react'

/** A demo, loaded when it first renders or ahead of that (`preload`: a Story menu's hover, the stories either side at idle), so a switch to it finds its chunk here. */
export type Demo = LazyExoticComponent<ComponentType> & { preload: () => Promise<unknown> }

function demo(load: () => Promise<{ default: ComponentType }>): Demo {
  let loading: Promise<{ default: ComponentType }> | undefined
  // One request however often it's asked for; a failed one is forgotten, so the next ask retries it.
  const preload = () => (loading ??= load().catch((error) => ((loading = undefined), Promise.reject(error))))
  return Object.assign(lazy(preload), { preload })
}

