// ---------------------------------------------------------------- theming

function ThemeFlip() {
  const flip = () => {
    const root = document.documentElement
    root.setAttribute('data-theme', root.getAttribute('data-theme') === 'dark' ? 'light' : 'dark')
  }
  return (
    <div className="flex flex-col items-center gap-5">
      <div className="flex flex-wrap gap-4">
        <figure className="flex flex-col items-center gap-2 rounded-xl border border-line bg-surface p-4">
          <LottiePlayer src={SAMPLES['logo-sting.lottie']} autoplay className="h-[135px] w-[240px]" />
          <figcaption className="font-mono text-xs text-fg-subtle">fg · line · accent</figcaption>
        </figure>
        <figure className="flex flex-col items-center gap-2 rounded-xl border border-line bg-surface p-4">
          <LottiePlayer src={SAMPLES['upload-progress.json']} autoplay loop className="size-[135px]" />
          <figcaption className="font-mono text-xs text-fg-subtle">slots by token name</figcaption>
        </figure>
        <figure className="flex flex-col items-center gap-2 rounded-xl border border-line bg-surface p-4">
          <LottiePlayer src={SAMPLES['success-check.json']} autoplay slots={{ success: 'accent' }} className="size-[135px]" />
          <figcaption className="font-mono text-xs text-fg-subtle">{'slots={{ success: "accent" }}'}</figcaption>
        </figure>
      </div>
      <button
        type="button"
        onClick={flip}
        className="rounded-lg border border-line bg-well px-3.5 py-2 text-sm font-medium focus-visible:ring-2 focus-visible:ring-accent focus-visible:outline-none"
      >
        Flip theme
      </button>
    </div>
  )
}

