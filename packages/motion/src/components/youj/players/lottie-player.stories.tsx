// ---------------------------------------------------------------- hero

type Phase = 'idle' | 'processing' | 'paid'

function Checkout() {
  const k = useYouj()
  const [phase, setPhase] = useState<Phase>('idle')

  useEffect(() => {
    if (phase !== 'processing') return
    const t = setTimeout(() => setPhase('paid'), k.ms('deliberate') * 3)
    return () => clearTimeout(t)
  }, [phase, k])

  return (
    <div className="w-full max-w-[360px] overflow-hidden rounded-2xl border border-line bg-surface shadow-sm">
      <div className="flex items-center justify-between border-b border-line px-5 py-3.5">
        <span className="text-sm font-medium">Checkout</span>
        <span className="font-mono text-xs text-fg-subtle">ORD-20418</span>
      </div>

      {phase === 'paid' ? (
        <div className="flex flex-col items-center px-6 pt-6 pb-7 text-center">
          <LottiePlayer src={SAMPLES['success-check.json']} playing className="size-24" label="Payment confirmed" />
          <p className="mt-3 text-base font-semibold tracking-tight">Payment confirmed</p>
          <p className="mt-1 text-sm text-fg-muted">$148.00 charged to Visa •••• 4242</p>
          <div className="mt-5 w-full rounded-lg bg-well px-4 py-3 text-left text-xs text-fg-muted">
            <div className="flex justify-between">
              <span>Receipt sent to</span>
              <span className="text-fg">ana@studio.dev</span>
            </div>
          </div>
          <button
            type="button"
            onClick={() => setPhase('idle')}
            className="mt-4 text-xs font-medium text-fg-muted underline-offset-4 hover:text-fg hover:underline focus-visible:rounded focus-visible:ring-2 focus-visible:ring-accent focus-visible:outline-none"
          >
            Start over
          </button>
        </div>
      ) : (
        <div className="px-5 pt-4 pb-5">
          <ul className="space-y-2.5 text-sm">
            <li className="flex justify-between">
              <span className="text-fg-muted">Pro plan · annual</span>
              <span>$144.00</span>
            </li>
            <li className="flex justify-between">
              <span className="text-fg-muted">Tax</span>
              <span>$4.00</span>
            </li>
            <li className="flex justify-between border-t border-line pt-2.5 font-medium">
              <span>Total</span>
              <span>$148.00</span>
            </li>
          </ul>
          <button
            type="button"
            disabled={phase === 'processing'}
            onClick={() => setPhase('processing')}
            className="mt-5 flex h-10 w-full items-center justify-center gap-2 rounded-lg bg-accent text-sm font-medium text-on-accent transition-opacity yj-duration-fast ease-standard focus-visible:ring-2 focus-visible:ring-accent focus-visible:ring-offset-2 focus-visible:ring-offset-surface focus-visible:outline-none disabled:opacity-80"
          >
            {phase === 'processing' ? (
              <>
                <LottiePlayer src={SAMPLES['upload-progress.json']} autoplay loop slots={{ line: 'color-mix(in oklab, var(--color-on-accent) 28%, transparent)', accent: 'on-accent', fg: 'on-accent' }} className="size-6" />
                Processing
              </>
            ) : (
              'Pay $148.00'
            )}
          </button>
        </div>
      )}
    </div>
  )
}

export const CheckoutSuccess: Story = {
  name: 'Hero: checkout success',
  render: () => <Checkout />,
}

