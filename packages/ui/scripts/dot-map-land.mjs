// Derives DotMap's land mask, src/components/ui/dot-map.land.tsx, from Natural
// Earth's 1:110m land polygons. Natural Earth is in the public domain
// (https://www.naturalearthdata.com/about/terms-of-use/), so the mask ships
// under the kit's own licence. Run it once when the grid changes; the output
// is committed, so nothing geographic is fetched or parsed at runtime:
//
//   node scripts/dot-map-land.mjs
//
// The grid is equirectangular: 3° cells from 180°W to 180°E and from 78°N to
// 57°S (Antarctica and the high Arctic are left out). A cell is land when a
// quarter of its 4 × 4 sample points fall on land, so narrow coasts and
// larger islands keep a dot.
import { writeFileSync } from 'node:fs'
import { join } from 'node:path'

const SOURCE = 'https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_110m_land.geojson'
const STEP = 3
const NORTH = 78
const SOUTH = -57
const SAMPLES = 4
const THRESHOLD = 0.25

const geo = await (await fetch(SOURCE)).json()
const polygons = geo.features.flatMap(({ geometry: g }) => (g.type === 'Polygon' ? [g.coordinates] : g.type === 'MultiPolygon' ? g.coordinates : []))

/** Even-odd ray cast against one ring of [lon, lat] points. */
function inRing(lon, lat, ring) {
  let inside = false
  for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
    const [xi, yi] = ring[i]
    const [xj, yj] = ring[j]
    if (yi > lat !== yj > lat && lon < ((xj - xi) * (lat - yi)) / (yj - yi) + xi) inside = !inside
  }
  return inside
}
const isLand = (lon, lat) => polygons.some(([outer, ...holes]) => inRing(lon, lat, outer) && !holes.some((hole) => inRing(lon, lat, hole)))

const cols = 360 / STEP
const rows = (NORTH - SOUTH) / STEP
const mask = Array.from({ length: rows }, (_, r) =>
  Array.from({ length: cols }, (_, c) => {
    let hits = 0
    for (let i = 0; i < SAMPLES; i++)
      for (let j = 0; j < SAMPLES; j++) if (isLand(-180 + (c + (i + 0.5) / SAMPLES) * STEP, NORTH - (r + (j + 0.5) / SAMPLES) * STEP)) hits++
    return hits / SAMPLES ** 2 >= THRESHOLD ? '#' : '.'
  }).join(''),
)

const file = `/* DotMap's land mask: the world on an equirectangular grid of ${STEP}° cells,
 * from 180°W to 180°E and ${NORTH}°N to ${-SOUTH}°S, one string per row from the
 * north, \`#\` for land. Generated by scripts/dot-map-land.mjs from Natural
 * Earth's 1:110m land (public domain, naturalearthdata.com). Don't edit by hand. */

export const LAND = {
  /** Degrees per cell. */
  step: ${STEP},
  /** The latitude of the first row's top edge. */
  north: ${NORTH},
  rows: [
${mask.map((row) => `    '${row}',`).join('\n')}
  ],
} as const
`
writeFileSync(join(import.meta.dirname, '../src/components/ui/dot-map.land.tsx'), file)
console.log(`dot-map.land.tsx: ${cols} × ${rows}, ${mask.join('').split('#').length - 1} land cells`)
