// Derives the Arc Globe block's dot globe, src/blocks/app/arc-globe/land.ts,
// from Natural Earth's 1:110m land polygons (public domain,
// https://www.naturalearthdata.com/about/terms-of-use/). Run it once when the
// spacing changes; the output is committed, so nothing geographic is fetched
// or parsed at runtime:
//
//   node scripts/globe-land.mjs
//
// The dots sit on rings of latitude STEP degrees apart, from SOUTH to NORTH,
// each ring holding as many dots as fit at STEP degrees of arc, so they're
// even across the sphere (no crowding toward the poles). A dot is land when
// its point falls on land. The mask is one bit per dot, ring by ring from the
// south and west to east, packed into base64.
import { writeFileSync } from 'node:fs'
import { join } from 'node:path'

const SOURCE = 'https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_110m_land.geojson'
const STEP = 1.8
const SOUTH = -56
const NORTH = 80

const geo = await (await fetch(SOURCE)).json()
const polygons = geo.features.flatMap(({ geometry: g }) => (g.type === 'Polygon' ? [g.coordinates] : g.type === 'MultiPolygon' ? g.coordinates : []))

/** Even-odd ray cast against one ring of [lon, lat] points. */
function inRing(lon, lat, ring) {
  let inside = false
  for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
    const [xi, yi] = ring[i]
    const [xj, yj] = ring[j]
    if (yi > lat !== yj > lat && lon < ((xj - xi) * (lat - yi)) / (yj - yi) + xi) inside = !inside
  }
  return inside
}
const isLand = (lon, lat) => polygons.some(([outer, ...holes]) => inRing(lon, lat, outer) && !holes.some((hole) => inRing(lon, lat, hole)))

const rings = Math.round((NORTH - SOUTH) / STEP)
const bits = []
for (let i = 0; i < rings; i++) {
  const lat = SOUTH + (i + 0.5) * STEP
  const count = Math.max(1, Math.round((360 * Math.cos((lat * Math.PI) / 180)) / STEP))
  for (let j = 0; j < count; j++) bits.push(isLand(-180 + ((j + 0.5) * 360) / count, lat) ? 1 : 0)
}
const bytes = new Uint8Array(Math.ceil(bits.length / 8))
bits.forEach((bit, i) => {
  if (bit) bytes[i >> 3] |= 1 << (i & 7)
})
const mask = Buffer.from(bytes).toString('base64')

const file = `/* The Arc Globe globe's land: dots on rings of latitude ${STEP}° apart,
 * from ${-SOUTH}°S to ${NORTH}°N, each ring holding as many as fit ${STEP}° of arc apart,
 * one bit per dot (1 on land), ring by ring from the south, west to east,
 * packed into base64. Generated by scripts/globe-land.mjs from Natural
 * Earth's 1:110m land (public domain, naturalearthdata.com). Don't edit by hand. */

const STEP = ${STEP}
const SOUTH = ${SOUTH}
const RINGS = ${rings}
const MASK = '${mask}'

/** The land dots as [longitude, latitude] pairs in degrees, decoded once. */
export function landDots(): Float32Array {
  const bytes = atob(MASK)
  const out: number[] = []
  let bit = 0
  for (let i = 0; i < RINGS; i++) {
    const lat = SOUTH + (i + 0.5) * STEP
    const count = Math.max(1, Math.round((360 * Math.cos((lat * Math.PI) / 180)) / STEP))
    for (let j = 0; j < count; j++, bit++) {
      if (bytes.charCodeAt(bit >> 3) & (1 << (bit & 7))) out.push(-180 + ((j + 0.5) * 360) / count, lat)
    }
  }
  return new Float32Array(out)
}
`
writeFileSync(join(import.meta.dirname, '../src/blocks/app/arc-globe/land.ts'), file)
console.log(`land.ts: ${rings} rings, ${bits.length} dots, ${bits.filter(Boolean).length} on land, ${mask.length} base64 chars`)
