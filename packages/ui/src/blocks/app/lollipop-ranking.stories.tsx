/** A level a day for 90 days around `level`, drifting by `drift` and jittered by `noise`, deterministic. */
function trace(seed: number, level: number, drift: number, noise = 0.004) {
  let x = seed
  const jitter = () => {
    x = (x * 16807) % 2147483647
    return (x - 1) / 2147483646 - 0.5
  }
  return Array.from({ length: 90 }, (_, day) => Math.min(1, level - drift * (1 - day / 89) + noise * jitter()))
}

