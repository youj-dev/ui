/** Even-odd ray cast against a flat [lon, lat, …] ring. */
function inside(ring: number[], lon: number, lat: number) {
  let hit = false
  for (let i = 0, j = ring.length - 2; i < ring.length; j = i, i += 2) {
    const [xi, yi, xj, yj] = [ring[i]!, ring[i + 1]!, ring[j]!, ring[j + 1]!]
    if (yi > lat !== yj > lat && lon < ((xj - xi) * (lat - yi)) / (yj - yi) + xi) hit = !hit
  }
  return hit
}

let landCache: string | undefined

/** Every land dot as one path of zero-length strokes: draw it with round caps. Computed once. */
export function landDots(): string {
  if (landCache !== undefined) return landCache
  const out: string[] = []
  for (let lat = LAT_MAX - DOT_STEP / 2; lat > LAT_MIN; lat -= DOT_STEP) {
    for (let lon = LON_MIN + DOT_STEP / 2; lon < LON_MAX; lon += DOT_STEP) {
      if (!LAND.some((ring) => inside(ring, lon, lat)) || WATER.some((ring) => inside(ring, lon, lat))) continue
      const [x, y] = project([lon, lat])
      out.push(`M${x} ${y}h0`)
    }
  }
  landCache = out.join('')
  return landCache
}

/* ── Routes ─────────────────────────────────────────────────────────────── */

export interface Route {
  /** The smoothed curve, for <path d>. */
  d: string
  /** Sampled points along it, [x0, y0, x1, y1, …]. */
  samples: Float64Array
  /** Distance from the start to each sample. */
  distance: Float64Array
  length: number
  box: { x0: number; y0: number; x1: number; y1: number }
}

const SAMPLES_PER_SEGMENT = 16

/** Waypoints → a Catmull-Rom curve through them (as cubic Béziers), sampled for lookups. */
export function buildRoute(waypoints: readonly LonLat[]): Route {
  const p = waypoints.map(project)
  const at = (i: number) => p[Math.max(0, Math.min(p.length - 1, i))]!
  const parts = [`M${p[0]![0].toFixed(1)} ${p[0]![1].toFixed(1)}`]
  const pts: number[] = [p[0]![0], p[0]![1]]
  for (let i = 0; i < p.length - 1; i++) {
    const [a, b, c, d] = [at(i - 1), at(i), at(i + 1), at(i + 2)]
    const c1: Point = [b[0] + (c[0] - a[0]) / 6, b[1] + (c[1] - a[1]) / 6]
    const c2: Point = [c[0] - (d[0] - b[0]) / 6, c[1] - (d[1] - b[1]) / 6]
    parts.push(`C${c1[0].toFixed(1)} ${c1[1].toFixed(1)} ${c2[0].toFixed(1)} ${c2[1].toFixed(1)} ${c[0].toFixed(1)} ${c[1].toFixed(1)}`)
    for (let s = 1; s <= SAMPLES_PER_SEGMENT; s++) {
      const t = s / SAMPLES_PER_SEGMENT
      const u = 1 - t
      pts.push(
        u * u * u * b[0] + 3 * u * u * t * c1[0] + 3 * u * t * t * c2[0] + t * t * t * c[0],
        u * u * u * b[1] + 3 * u * u * t * c1[1] + 3 * u * t * t * c2[1] + t * t * t * c[1],
      )
    }
  }
  const samples = Float64Array.from(pts)
  const distance = new Float64Array(samples.length / 2)
  const box = { x0: Infinity, y0: Infinity, x1: -Infinity, y1: -Infinity }
  for (let i = 0; i < distance.length; i++) {
    const x = samples[i * 2]!
    const y = samples[i * 2 + 1]!
    if (i > 0) distance[i] = distance[i - 1]! + Math.hypot(x - samples[i * 2 - 2]!, y - samples[i * 2 - 1]!)
    box.x0 = Math.min(box.x0, x)
    box.y0 = Math.min(box.y0, y)
    box.x1 = Math.max(box.x1, x)
    box.y1 = Math.max(box.y1, y)
  }
  return { d: parts.join(''), samples, distance, length: distance[distance.length - 1]!, box }
}

/** The point `progress` (0–1) of the way along a route, and the heading there in degrees. */
export function pointAt(route: Route, progress: number): { x: number; y: number; angle: number } {
  const target = Math.max(0, Math.min(1, progress)) * route.length
  const { distance, samples } = route
  let lo = 0
  let hi = distance.length - 1
  while (lo < hi - 1) {
    const mid = (lo + hi) >> 1
    if (distance[mid]! <= target) lo = mid
    else hi = mid
  }
  const span = distance[hi]! - distance[lo]! || 1
  const t = Math.max(0, Math.min(1, (target - distance[lo]!) / span))
  const [x0, y0, x1, y1] = [samples[lo * 2]!, samples[lo * 2 + 1]!, samples[hi * 2]!, samples[hi * 2 + 1]!]
  return { x: x0 + (x1 - x0) * t, y: y0 + (y1 - y0) * t, angle: (Math.atan2(y1 - y0, x1 - x0) * 180) / Math.PI }
}

/** Where along a route (0–1) it passes closest to a point. */
export function nearestProgress(route: Route, x: number, y: number): number {
  let best = 0
  let bestDistance = Infinity
  for (let i = 0; i < route.distance.length; i++) {
    const d = Math.hypot(route.samples[i * 2]! - x, route.samples[i * 2 + 1]! - y)
    if (d < bestDistance) {
      bestDistance = d
      best = i
    }
  }
  return route.distance[best]! / route.length
}
