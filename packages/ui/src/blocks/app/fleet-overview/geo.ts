/* The fleet map's geometry, with no map data and no network: a coarse outline
 * of the land as lon/lat polygons, rasterized into a dot grid, and sea lanes
 * as waypoints smoothed into curves. The projection is equirectangular, four
 * map units to a degree. Routes are sampled in plain math (not the DOM's
 * getPointAtLength), so positions, headings and progress work the same on
 * the server, in tests and in the browser. */

export type LonLat = readonly [lon: number, lat: number]
export type Point = readonly [x: number, y: number]

const LON_MIN = -100
const LON_MAX = 160
const LAT_MIN = -50
const LAT_MAX = 72
const UNIT = 4

export const MAP_WIDTH = (LON_MAX - LON_MIN) * UNIT
export const MAP_HEIGHT = (LAT_MAX - LAT_MIN) * UNIT
/** Degrees between dots. */
export const DOT_STEP = 2
/** Map units between dots. */
export const DOT_PITCH = DOT_STEP * UNIT

export function project([lon, lat]: LonLat): Point {
  return [(lon - LON_MIN) * UNIT, (LAT_MAX - lat) * UNIT]
}

