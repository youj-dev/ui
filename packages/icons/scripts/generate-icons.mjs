// Generates the icon barrel (src/components/youj/icons/index.ts) and the
// icon registry fragment (registry/icons.json) from the icon files themselves,
// so parallel icon work never conflicts on shared lists. Run after adding icons:
//
//   node scripts/generate-icons.mjs          write both files
//   node scripts/generate-icons.mjs --check  exit 1 if either is stale
import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const root = new URL('..', import.meta.url).pathname
const dir = join(root, 'src/components/youj/icons')
const rel = 'src/components/youj/icons'
const check = process.argv.includes('--check')

const icons = []
for (const file of readdirSync(dir).sort()) {
  if (!file.endsWith('.tsx') || /\.(stories|test)\.tsx$/.test(file) || ['icon-base.tsx', 'youj-icon.tsx'].includes(file)) continue
  const src = readFileSync(join(dir, file), 'utf8')
  // Only the JSDoc block directly above the export: `(?:(?!\*\/)[\s\S])*` cannot cross an earlier comment's end.
  const m = src.match(/(?:\/\*\*((?:(?!\*\/)[\s\S])*)\*\/\s*)?export const (\w+Icon) = createIcon\(\{\s*name: '([^']+)'/)
  if (!m) continue
  const description = (m[1] ?? '')
    .split('\n')
    .map((line) => line.replace(/^\s*\*\s?/, '').trim())
    .filter(Boolean)
    .join(' ')
  icons.push({ file: file.replace(/\.tsx$/, ''), component: m[2], name: m[3], description })
}

// Acronyms keep their capitals in display names ("App AI Workspace", not "App Ai Workspace").
const ACRONYMS = { ai: 'AI', api: 'API', cms: 'CMS', cta: 'CTA', faq: 'FAQ', otp: 'OTP', kpi: 'KPI', sso: 'SSO', seo: 'SEO', csv: 'CSV', url: 'URL', ui: 'UI', id: 'ID', pdf: 'PDF', crm: 'CRM', sms: 'SMS', json: 'JSON', qr: 'QR', cpu: 'CPU', rss: 'RSS', svg: 'SVG', mcp: 'MCP', cli: 'CLI', saas: 'SaaS' }
const title = (name) => name.split('-').map((w) => ACRONYMS[w] ?? w[0].toUpperCase() + w.slice(1)).join(' ')

const index = `// Generated by scripts/generate-icons.mjs. Do not edit by hand.
// The full set, for stories, tests and apps that want everything. Registry items copy files individually.
import type { YoujIconComponent } from './icon-base'
${icons.map((i) => `import { ${i.component} } from './${i.file}'`).join('\n')}

export {
  createIcon,
  ICON_CATEGORIES,
  origin,
  seq,
  seqFor,
  after,
  drawIn,
  drawOut,
  drawn,
  hidden,
  type IconCategory,
  type IconProps,
  type IconMeta,
  type IconVariants,
  type IconContext,
  type IconDefinition,
  type YoujIconComponent,
  type IconLoop,
  type IconTrigger,
} from './icon-base'
export {
  YoujIcon,
  type YoujIconEffect,
  type YoujIconIntensity,
  type YoujIconDirection,
  type YoujIconProps,
} from './youj-icon'
export { IconSwap, type IconSwapProps, type IconSwapTransition, type IconSwapDirection, type SwapIcon } from './icon-swap'
export { useIconState, type UseIconStateOptions, type IconState, type IconStateButtonProps } from './use-icon-state'
export {
${icons.map((i) => `  ${i.component},`).join('\n')}
}

export const icons: YoujIconComponent[] = [
${icons.map((i) => `  ${i.component},`).join('\n')}
]
`

const registry = [
  {
    name: 'icon-engine',
    type: 'registry:lib',
    title: 'Icon engine',
    description:
      'createIcon() factory, IconProps (size, strokeWidth, aria-label, trigger hover|mount|loop|none, controlled active), choreography helpers and useIconTrigger (parent-button / data-yj-trigger hover, focus-visible, offscreen-paused loops, reduced motion).',
    dependencies: ['motion'],
    registryDependencies: ['youj-core'],
    files: [
      { path: `${rel}/icon-base.tsx`, type: 'registry:lib' },
      { path: `${rel}/use-icon-trigger.ts`, type: 'registry:lib' },
    ],
  },
  {
    name: 'youj-icon',
    type: 'registry:component',
    title: 'YoujIcon',
    description:
      'Adds 22 youj effects (pop, wiggle, spin, nudge, pulse, ring, bounce, flip, swing, float, heartbeat, shake, jelly, orbit, tilt, zoom-in/out and five draw modes) to any lucide-react icon, with intensity and RTL-aware direction, on the same triggers as the animated set.',
    dependencies: ['motion'],
    registryDependencies: ['icon-engine'],
    files: [{ path: `${rel}/youj-icon.tsx`, type: 'registry:component' }],
  },
  ...icons.map((i) => ({
    name: `icon-${i.name}`,
    type: 'registry:component',
    title: `${title(i.name)} icon`,
    description: i.description,
    dependencies: ['motion'],
    registryDependencies: ['icon-engine'],
    files: [{ path: `${rel}/${i.file}.tsx`, type: 'registry:component' }],
  })),
  {
    name: 'icons',
    type: 'registry:component',
    title: 'Youj icon set',
    description: `All ${icons.length} animated icons, YoujIcon and the engine, with an index that exports them plus an \`icons\` array.`,
    dependencies: ['motion'],
    registryDependencies: ['icon-engine', 'youj-icon', 'icon-swap', 'icon-morph', 'use-icon-state', ...icons.map((i) => `icon-${i.name}`)],
    files: [{ path: `${rel}/index.ts`, type: 'registry:component' }],
  },
]
const registryJson = JSON.stringify(registry, null, 2) + '\n'

const targets = [
  [join(dir, 'index.ts'), index],
  [join(root, 'registry/icons.json'), registryJson],
]
if (check) {
  const stale = targets.filter(([p, next]) => readFileSync(p, 'utf8') !== next).map(([p]) => p)
  if (stale.length) {
    console.error(`stale (run node scripts/generate-icons.mjs):\n  ${stale.join('\n  ')}`)
    process.exit(1)
  }
} else {
  for (const [p, next] of targets) writeFileSync(p, next)
}
console.log(`icons: ${icons.length}`)
