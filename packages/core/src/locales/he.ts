type Forms = { one: string; two: string; other: string }
/** The phrase for `n` by Hebrew's plural forms (one, two, other); `#` is the number, shown as `shown` when the caller formatted it. */
const plural = (n: number, forms: Forms, shown = num(n)) => (forms[rules.select(n) as keyof Forms] ?? forms.other).replace('#', shown)

/** Keeps a value's own direction inside Hebrew text (FSI … PDI). */
const iso = (text: string) => `\u2068${text}\u2069`
const quote = (text: string) => `“${iso(text)}”`

/** The table's default noun, counted in its own forms; an app's own noun follows its count as given. */
const ROWS = 'שורות'
