const rules = new Intl.PluralRules('pl')
const num = new Intl.NumberFormat('pl').format
const or = new Intl.ListFormat('pl', { type: 'disjunction' })
const and = new Intl.ListFormat('pl', { type: 'conjunction' })
const seconds = new Intl.NumberFormat('pl', { style: 'unit', unit: 'second', unitDisplay: 'narrow', minimumFractionDigits: 1, maximumFractionDigits: 1 })
const ms = new Intl.NumberFormat('pl', { style: 'unit', unit: 'millisecond', unitDisplay: 'narrow', maximumFractionDigits: 0 })

/** The form of a word for `n`: one (1), few (2–4, 22–24…), many (0, 5–21, 25…), other (fractions). */
const plural = (n: number, forms: { one: string; few: string; many: string; other: string }) => {
  const category = rules.select(n)
  return category === 'one' || category === 'few' || category === 'many' ? forms[category] : forms.other
}
/** A count the component already formatted ("1 234"), read back for its plural form. */
const countOf = (text: string) => Number(text.replace(/\D/g, ''))

/** The table's default noun is the genitive plural; after a count it takes the count's form. An app's own noun is used as given. */
const ROWS = 'wierszy'
const nounFor = (n: number, noun: string) => (noun === ROWS ? plural(n, { one: 'wiersz', few: 'wiersze', many: 'wierszy', other: 'wiersza' }) : noun)
const genitive = (n: number, noun: string) => (noun === ROWS && rules.select(n) === 'one' ? 'wiersza' : noun)

/** The prompt counter's default unit, in the count's form. */
const CHARS = 'znaków'
const chars = (n: number, unit: string) => (unit === CHARS ? plural(n, { one: 'znak', few: 'znaki', many: 'znaków', other: 'znaku' }) : unit)

const lower = (text: string) => text.toLocaleLowerCase('pl')
const quote = (text: string) => `„${text}”`
const files = (n: number) => `${num(n)} ${plural(n, { one: 'plik', few: 'pliki', many: 'plików', other: 'pliku' })}`
const fields = (n: number) => `${num(n)} ${plural(n, { one: 'pole', few: 'pola', many: 'pól', other: 'pola' })}`
const tags = (n: number) => `${num(n)} ${plural(n, { one: 'tag', few: 'tagi', many: 'tagów', other: 'tagu' })}`
