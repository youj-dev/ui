type Forms = Partial<Record<Intl.LDMLPluralRule, string>> & { other: string }
/** The phrase for `n` by Arabic's six plural forms; `#` is the number, shown as `shown` when the caller formatted it. */
const plural = (n: number, forms: Forms, shown = num(n)) => (forms[rules.select(n)] ?? forms.other).replace('#', shown)

/** Keeps a value's own direction inside Arabic text (FSI … PDI). */
const iso = (text: string) => `\u2068${text}\u2069`
const quote = (text: string) => `«${iso(text)}»`
/** An app's plural noun with the definite article: "طلبات" → "الطلبات". */
const def = (noun: string) => (noun.startsWith('ال') ? noun : `ال${noun}`)

/** The table's default noun, counted in its own forms; an app's own noun follows its count in brackets. */
const ROWS = 'صفوف'
const ROW_FORMS: Forms = { zero: '# صف', one: 'صف واحد', two: 'صفّين', few: '# صفوف', many: '# صفًا', other: '# صف' }
const nounFor = (count: string, n: number, noun: string) => (noun === ROWS ? plural(n, ROW_FORMS, count) : `${def(noun)} (${count})`)

const fields = (n: number) => plural(n, { zero: '# حقل', one: 'حقل واحد', two: 'حقلين', few: '# حقول', many: '# حقلًا', other: '# حقل' })
const files = (n: number) => plural(n, { zero: '# ملف', one: 'ملف واحد', two: 'ملفين', few: '# ملفات', many: '# ملفًا', other: '# ملف' })
const tags = (n: number) => plural(n, { zero: '# وسم', one: 'وسم واحد', two: 'وسمين', few: '# وسوم', many: '# وسمًا', other: '# وسم' })
