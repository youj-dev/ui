/** The final consonant (받침) of a word's last Hangul syllable: 0 for none, 8 for ㄹ, null when it isn't Hangul. */
function final(word: string) {
  const code = word.trimEnd().charCodeAt(word.trimEnd().length - 1)
  return code >= 0xac00 && code <= 0xd7a3 ? (code - 0xac00) % 28 : null
}

/** A word with the particle its last syllable takes ("파일을", "사진을", "이미지를"); "을(를)" for names that aren't Hangul. */
const josa = (word: string, afterConsonant: string, afterVowel: string) => {
  const f = final(word)
  return `${word}${f === null ? `${afterConsonant}(${afterVowel})` : f ? afterConsonant : afterVowel}`
}

/** "(으)로": 로 after a vowel or ㄹ, 으로 after other consonants. */
const ro = (word: string) => {
  const f = final(word)
  return `${word}${f === null ? '(으)로' : f === 0 || f === 8 ? '로' : '으로'}`
}

