const sha256 = async (value: string) => new Uint8Array(await crypto.subtle.digest('SHA-256', new TextEncoder().encode(value)))

async function authorized(request: Request, token: string | undefined): Promise<boolean> {
  if (!token) return true
  const bearer = request.headers.get('authorization')?.match(/^Bearer (.+)$/)?.[1]?.trim()
  if (!bearer) return false
  // Compare digests in full, so the time taken says nothing about how much of the key matched.
  const [a, b] = await Promise.all([sha256(bearer), sha256(token)])
  return a.every((byte, i) => byte === b[i])
}

/** The largest request body taken: a tool call is a few hundred bytes. */
const MAX_BODY_BYTES = 64 * 1024

/** The body as text, or undefined once it passes the cap: counted as it streams in, since Content-Length may be absent or wrong. */
async function readCapped(request: Request): Promise<string | undefined> {
  const declared = Number(request.headers.get('content-length'))
  if (declared > MAX_BODY_BYTES) return undefined
  if (!request.body) return ''
  const reader = request.body.getReader()
  const chunks: Uint8Array[] = []
  let size = 0
  for (;;) {
    const { done, value } = await reader.read()
    if (done) break
    size += value.byteLength
    if (size > MAX_BODY_BYTES) {
      await reader.cancel()
      return undefined
    }
    chunks.push(value)
  }
  return new TextDecoder().decode(await new Blob(chunks as BlobPart[]).arrayBuffer())
}

const text = (body: string, status = 200, headers: HeadersInit = {}) => new Response(body, { status, headers: { 'content-type': 'text/plain; charset=utf-8', ...headers } })

export default {
  async fetch(request: Request, env: { STEALTH_TOKEN?: string; ASSETS?: Assets } = {}): Promise<Response> {
    const { pathname } = new URL(request.url)
    if (pathname !== '/') return text('Not found', 404)
    const browsing = (request.method === 'GET' && !request.headers.get('accept')?.includes('text/event-stream')) || request.method === 'HEAD'
    if (browsing) return text(NOTE)
    if (!(await authorized(request, env.STEALTH_TOKEN))) return text('Unauthorized: send the Youj key as a bearer token', 401, { 'www-authenticate': 'Bearer' })
    if (request.method !== 'POST' && request.method !== 'GET' && request.method !== 'DELETE') return text('Method not allowed', 405, { allow: 'GET, POST, DELETE, HEAD' })
    let forwarded = request
    if (request.method === 'POST') {
      const body = await readCapped(request)
      if (body === undefined) return text('Request body too large (64 KB at most)', 413)
      forwarded = new Request(request, { body })
    }
    const transport = new WebStandardStreamableHTTPServerTransport({ enableJsonResponse: true })
    await createServer(catalogFor(env.ASSETS), { remote: true }).connect(transport)
    return transport.handleRequest(forwarded)
  },
}
