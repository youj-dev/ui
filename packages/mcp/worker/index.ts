/* The Youj MCP server over Streamable HTTP, at https://mcp.youj.dev. Read-only and stateless:
 * each request gets a fresh server over the index bundled into this Worker (data/, generated by
 * `pnpm -F @youj/mcp generate`), so there is no session or storage. The block files are not in the bundle: they are
 * static assets (data/sources/, one file each, the ASSETS binding), fetched when a tool call needs one and kept for the life of the isolate. While the site is gated, the
 * STEALTH_TOKEN secret (the same key the CLI sends to the site) locks the MCP to requests that send it
 * as a bearer token; without the secret, it is public. A request body over 64 KB is refused with 413. A browser
 * (a GET that doesn't ask for an event stream) gets the note on how to connect instead. */

type Assets = { fetch(request: Request): Promise<Response> }

const index = { meta, components, illustrations, loaders, miniatures, props, hooks, blocks, icons, lucide, pairs, effects, transitions, uiTokens, docs } as unknown as YoujIndex

// One catalog per isolate, made on the first request, which is the first time the ASSETS binding is in hand.
let catalog: Catalog | undefined
function catalogFor(assets: Assets | undefined): Catalog {
  const host: Host = {
    ...bareHost,
    async source(file) {
      if (!assets) return undefined
      const response = await assets.fetch(new Request(new URL(encodeURI(file), 'https://assets.youj.dev/')))
      return response.ok ? response.text() : (await response.body?.cancel(), undefined)
    },
  }
  return (catalog ??= new Catalog(index, host))
}

